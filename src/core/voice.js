import { settings } from './settings.js';
import { audio, ctx, voiceGain, stopSfx } from './audio.js';
import { rand } from './util.js';

// ---------- speech ----------
let voice = null;
function pickVoice() {
  const vs = speechSynthesis.getVoices();
  if (!vs.length) return;
  const enIN = vs.filter((v) => v.lang.replace('_', '-').startsWith('en-IN'));
  const en = vs.filter((v) => v.lang.startsWith('en'));
  voice =
    enIN.find((v) => /natural|neural|premium|enhanced/i.test(v.name)) ||
    enIN[0] ||
    en.find((v) => /natural|neural|premium|enhanced/i.test(v.name)) ||
    en.find((v) => /Samantha|Google US English|Aria|Jenny|Karen|Zira|Susan|Female/i.test(v.name)) ||
    en[0] || vs[0];
}
if ('speechSynthesis' in window) {
  pickVoice();
  speechSynthesis.onvoiceschanged = pickVoice;
}
// Voice = pre-recorded clips in audio/ (generated by tools/gen_audio.py),
// Web Speech TTS only as fallback if a clip is missing. One voice at a
// time: new speech stops the old; queue:true plays after, never on top.
let curSrc = null;
let ttsActive = false;
let voiceActive = false;
let voiceToken = 0; // bumped on every new voice action — stale callbacks are ignored
const voiceQueue = [];
const voiceBusy = () => voiceActive;
const bufCache = new Map(); // LRU of decoded AudioBuffers, max 30 — keyed by URL
const inflight = new Map(); // dedupe concurrent loads
function loadClip(url) {
  const hit = bufCache.get(url);
  if (hit) {
    bufCache.delete(url);
    bufCache.set(url, hit);
    return Promise.resolve(hit);
  }
  if (inflight.has(url)) return inflight.get(url);
  const p = fetch(url)
    .then((r) => { if (!r.ok) throw new Error(r.status); return r.arrayBuffer(); })
    .then((ab) => new Promise((res, rej) => audio().decodeAudioData(ab, res, rej)))
    .then((buf) => {
      inflight.delete(url);
      bufCache.set(url, buf);
      if (bufCache.size > 30) bufCache.delete(bufCache.keys().next().value);
      return buf;
    })
    .catch((e) => { inflight.delete(url); throw e; });
  inflight.set(url, p);
  return p;
}

// ---------- family voice packs ----------
// Recorded takes live in audio/voices/<voice>/<clip>~<id>.m4a with a manifest.
// The session voice is chosen once per page load; missing takes fall back to
// the bundled Tara clips, then TTS.
let voiceManifest = { packs: {}, voices: {} };
let sessionVoice = null;
const lastTake = new Map(); // clip key -> last take file played
const manifestListeners = new Set();
export const onVoiceManifest = (fn) => manifestListeners.add(fn);
export const packName = (s) =>
  (voiceManifest.packs && voiceManifest.packs[s] && voiceManifest.packs[s].name) || s;
export const packsWithTakes = () => Object.keys(voiceManifest.voices || {}).filter((s) =>
  Object.values(voiceManifest.voices[s] || {}).some((t) => t.length));
export const todayVoiceName = () => (sessionVoice ? packName(sessionVoice) : 'Tara');
export function loadVoiceManifest() {
  return fetch(`audio/voices/manifest.json?v=${Date.now()}`, { cache: 'no-store' })
    .then((r) => (r.ok ? r.json() : null))
    .then((j) => {
      if (j && j.voices) voiceManifest = j;
      pickSessionVoice();
      manifestListeners.forEach((fn) => fn());
    })
    .catch(() => {});
}
loadVoiceManifest();
export function pickSessionVoice() {
  const avail = packsWithTakes();
  // a saved pack that vanished or has no takes behaves like surprise
  if (settings.voicePack !== 'surprise' && avail.includes(settings.voicePack)) {
    sessionVoice = settings.voicePack;
    return;
  }
  sessionVoice = avail.length ? rand(avail) : null;
}
function voiceClipUrls(key) {
  const urls = [];
  if (sessionVoice) {
    const v = voiceManifest.voices[sessionVoice] || {};
    let takes = v[key];
    if ((!takes || !takes.length) && /^cheer_\d+$/.test(key) && v.cheer && v.cheer.length) takes = v.cheer;
    if ((!takes || !takes.length) && key === 'try_again' && v.try && v.try.length) takes = v.try;
    if (takes && takes.length) {
      let f = rand(takes);
      if (takes.length > 1) {
        const prev = lastTake.get(key);
        while (f === prev) f = rand(takes);
      }
      lastTake.set(key, f);
      urls.push(`audio/voices/${sessionVoice}/${f}`);
    }
  }
  urls.push(`audio/${key}.m4a`);
  return urls;
}

function speakTts(text, pitch, rate, my) {
  if (!('speechSynthesis' in window)) { if (voiceToken === my) { voiceActive = false; flushQueue(); } return; }
  const u = new SpeechSynthesisUtterance(text);
  if (voice) u.voice = voice;
  u.pitch = pitch;
  u.rate = rate;
  u.volume = settings.volume;
  ttsActive = true;
  u.onend = u.onerror = () => { if (voiceToken === my) { ttsActive = false; voiceActive = false; flushQueue(); } };
  speechSynthesis.speak(u);
}
function flushQueue() {
  const next = voiceQueue.shift();
  if (next) startVoice(next);
}
function startVoice({ text, clip, pitch, rate }) {
  const my = ++voiceToken;
  voiceActive = true;
  if (clip) {
    const urls = voiceClipUrls(clip);
    const tryPlay = (i) => loadClip(urls[i]).then((buf) => {
      if (voiceToken !== my) return;
      const src = ctx.createBufferSource();
      src.buffer = buf;
      src.connect(voiceGain);
      src.onended = () => {
        src.disconnect();
        if (voiceToken === my) { curSrc = null; voiceActive = false; flushQueue(); }
      };
      curSrc = src;
      src.start();
    }).catch(() => {
      if (voiceToken !== my) return;
      if (i + 1 < urls.length) tryPlay(i + 1);
      else speakTts(text, pitch, rate, my);
    });
    tryPlay(0);
  } else {
    speakTts(text, pitch, rate, my);
  }
}
export function say(text, { pitch = 1.15, rate = 0.92, queue = false, clip = null } = {}) {
  if (!settings.voice) return;
  audio();
  if (queue && voiceBusy()) { voiceQueue.push({ text, clip, pitch, rate }); return; }
  stopVoice();
  startVoice({ text, clip, pitch, rate });
}
export function stopVoice() {
  voiceToken++;
  voiceQueue.length = 0;
  if (curSrc) {
    curSrc.onended = null;
    try { curSrc.stop(); } catch (e) {}
    curSrc.disconnect();
    curSrc = null;
  }
  if (ttsActive && 'speechSynthesis' in window) speechSynthesis.cancel();
  ttsActive = false;
  voiceActive = false;
}
export function stopAllAudio() {
  stopSfx();
  stopVoice();
}
